const fs = require('fs')
const path = require('path')

const version = process.env.NIGHTFALL_BUILD_VERSION
  || process.env.NEXT_PUBLIC_BUILD_VERSION
  || process.env.VERCEL_GIT_COMMIT_SHA
  || `${new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14)}-${Math.random().toString(36).slice(2, 8)}`

const dir = path.join(__dirname, '..', 'lib', 'generated')
fs.mkdirSync(dir, { recursive: true })
fs.writeFileSync(
  path.join(dir, 'build-version.ts'),
  `// Auto-generated by scripts/write-build-version.cjs during builds.\nexport const NIGHTFALL_BUILD_VERSION = ${JSON.stringify(version)}\n`
)
console.log(`Nightfall build version: ${version}`)
